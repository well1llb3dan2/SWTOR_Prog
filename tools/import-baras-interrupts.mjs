import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const ref = process.env.BARAS_REF ?? "master";
const response = await fetch(`https://raw.githubusercontent.com/baras-app/baras/${ref}/core/data/interrupts.csv`);
if (!response.ok) throw new Error(`BARAS interrupt table request failed: ${response.status}`);
const ids = [...new Set((await response.text()).match(/\b\d{12,}\b/g) ?? [])].sort();
const output = `// Generated by tools/import-baras-interrupts.mjs from BARAS ${ref}.\n// Do not edit manually. Re-run the importer when the BARAS reference changes.\n\nexport const BARAS_INTERRUPT_CATALOG_VERSION = ${JSON.stringify(ref)} as const;\nexport const BARAS_INTERRUPT_ABILITY_IDS: ReadonlySet<string> = new Set(${JSON.stringify(ids, null, 2)});\n`;
const outputPath = resolve(repoRoot, "packages/game-data/src/generated/baras-interrupts.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`Generated ${ids.length} BARAS interrupt ability ids.`);
