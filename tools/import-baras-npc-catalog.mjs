import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const barasRef = process.env.BARAS_REF ?? "master";
const treeUrl = `https://api.github.com/repos/baras-app/baras/git/trees/${barasRef}?recursive=1`;
const headers = { "User-Agent": "SWTOR_Prog-BARAS-catalog-import" };

function extractOne(pattern, text) {
  return text.match(pattern)?.[1] ?? null;
}

function stripTomlComments(value) {
  return value
    .split(/\r?\n/)
    .map((line) => line.replace(/\s+#.*$/, ""))
    .join("\n");
}

function parseIds(block) {
  const raw = extractOne(/ids\s*=\s*\[([\s\S]*?)\]/, stripTomlComments(block));
  if (raw === null) return [];
  return [...raw.matchAll(/\b\d{12,}\b/g)].map((match) => match[0]);
}

function parseEntity(block) {
  const clean = stripTomlComments(block);
  const name = extractOne(/name\s*=\s*"([^"]+)"/, clean);
  const ids = parseIds(block);
  if (name === null || ids.length === 0) return null;
  return {
    name,
    ids: [...new Set(ids)],
    isBoss: extractOne(/is_boss\s*=\s*(true|false)/, clean) === "true",
    isKillTarget: extractOne(/is_kill_target\s*=\s*(true|false)/, clean) === "true",
    triggersEncounter: extractOne(/triggers_encounter\s*=\s*(true|false)/, clean) === "true",
    singleInstance: extractOne(/single_instance\s*=\s*(true|false)/, clean) === "true",
  };
}

function contextBefore(text, offset) {
  const before = text.slice(0, offset);
  const bossStart = before.lastIndexOf("[[boss]]");
  const bossBlock = bossStart === -1 ? "" : before.slice(bossStart);
  return {
    bossId: extractOne(/\bid\s*=\s*"([^"]+)"/, bossBlock) ?? "unknown-boss",
    bossName: extractOne(/\bname\s*=\s*"([^"]+)"/, bossBlock) ?? "Unknown Boss",
  };
}

const treeResponse = await fetch(treeUrl, { headers });
if (!treeResponse.ok) throw new Error(`BARAS tree request failed: ${treeResponse.status}`);
const tree = await treeResponse.json();
const resolvedBarasRef = tree.sha ?? barasRef;
const paths = tree.tree
  .filter((entry) => entry.type === "blob" && /^core\/definitions\/encounters\/(operations|flashpoints|other)\/.*\.toml$/.test(entry.path))
  .map((entry) => entry.path)
  .sort();

const records = [];
for (const source of paths) {
  const response = await fetch(`https://raw.githubusercontent.com/baras-app/baras/${resolvedBarasRef}/${source}`);
  if (!response.ok) throw new Error(`BARAS definition request failed for ${source}: ${response.status}`);
  const text = await response.text();
  const areaName = extractOne(/\[area\][\s\S]*?\bname\s*=\s*"([^"]+)"/, text) ?? "Unknown Area";
  for (const match of text.matchAll(/\[\[boss\.entities\]\]/g)) {
    const entity = parseEntity(text.slice(match.index));
    if (entity === null) continue;
    const context = contextBefore(text, match.index);
    for (const npcId of entity.ids) {
      records.push({
        npcId,
        name: entity.name,
        role: entity.isBoss ? "boss" : "mechanic",
        isKillTarget: entity.isKillTarget,
        triggersEncounter: entity.triggersEncounter,
        singleInstance: entity.singleInstance,
        encounterId: context.bossId,
        encounterName: context.bossName,
        operationName: areaName,
        source,
      });
    }
  }
}

const byId = new Map();
for (const record of records) {
  const existing = byId.get(record.npcId);
  if (existing === undefined) {
    byId.set(record.npcId, { ...record, names: [record.name], ambiguous: false });
    continue;
  }
  if (!existing.names.includes(record.name)) existing.names.push(record.name);
  existing.ambiguous ||= existing.role !== record.role || existing.encounterId !== record.encounterId || existing.operationName !== record.operationName;
  existing.isKillTarget ||= record.isKillTarget;
  existing.triggersEncounter ||= record.triggersEncounter;
  existing.singleInstance ||= record.singleInstance;
}

const entries = [...byId.values()].sort((left, right) => left.npcId.localeCompare(right.npcId));
const output = `// Generated by tools/import-baras-npc-catalog.mjs from BARAS ${resolvedBarasRef}.\n// Do not edit manually. Re-run the importer when the BARAS reference changes.\n\nexport interface BarasNpcCatalogEntry {\n  npcId: string;\n  name: string;\n  names: string[];\n  role: \"boss\" | \"mechanic\";\n  isKillTarget: boolean;\n  triggersEncounter: boolean;\n  singleInstance: boolean;\n  encounterId: string;\n  encounterName: string;\n  operationName: string;\n  source: string;\n  ambiguous: boolean;\n}\n\nexport const BARAS_NPC_CATALOG_SOURCE = \"baras\" as const;\nexport const BARAS_NPC_CATALOG_VERSION = ${JSON.stringify(resolvedBarasRef)} as const;\nexport const BARAS_NPC_CATALOG: readonly BarasNpcCatalogEntry[] = ${JSON.stringify(entries, null, 2)};\nexport const BARAS_NPC_CATALOG_BY_ID = new Map(BARAS_NPC_CATALOG.map((entry) => [entry.npcId, entry]));\n`;

const outputPath = resolve(repoRoot, "packages/game-data/src/generated/baras-npc-catalog.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`Generated ${entries.length} unique NPC ids from ${paths.length} BARAS definitions at ${outputPath}`);
