import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const ref = process.env.BARAS_REF ?? "master";
const response = await fetch(`https://raw.githubusercontent.com/baras-app/baras/${ref}/core/data/off_gcd.json`);
if (!response.ok) throw new Error(`BARAS off-GCD table request failed: ${response.status}`);
const data = await response.json();
const ids = Object.keys(data).filter((id) => /^\d{12,}$/.test(id)).sort();
const output = `// Generated by tools/import-baras-off-gcd.mjs from BARAS ${ref}.\n// Do not edit manually. Re-run the importer when the BARAS reference changes.\n\nexport const BARAS_OFF_GCD_CATALOG_VERSION = ${JSON.stringify(ref)} as const;\nexport const BARAS_OFF_GCD_ABILITY_IDS: ReadonlySet<string> = new Set(${JSON.stringify(ids, null, 2)});\n`;
const outputPath = resolve(repoRoot, "packages/game-data/src/generated/baras-off-gcd.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`Generated ${ids.length} BARAS off-GCD ability ids.`);
