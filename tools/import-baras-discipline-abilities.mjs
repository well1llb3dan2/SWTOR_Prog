import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const ref = process.env.BARAS_REF ?? "master";
const response = await fetch(`https://raw.githubusercontent.com/baras-app/baras/${ref}/core/data/discipline_unique_abilities.csv`);
if (!response.ok) throw new Error(`BARAS discipline ability table request failed: ${response.status}`);
const lines = (await response.text()).split(/\r?\n/).filter(Boolean);
const entries = lines.slice(1).map((line) => {
  const [discipline, disciplineId, ability, abilityId] = line.split(",");
  return discipline && disciplineId && ability && abilityId && /^\d{12,}$/.test(abilityId)
    ? { discipline, disciplineId, ability, abilityId }
    : null;
}).filter((entry) => entry !== null);
const byAbilityId = new Map();
for (const entry of entries) {
  const existing = byAbilityId.get(entry.abilityId);
  if (existing === undefined) byAbilityId.set(entry.abilityId, { ...entry, disciplines: [entry.discipline] });
  else if (!existing.disciplines.includes(entry.discipline)) existing.disciplines.push(entry.discipline);
}
const output = `// Generated by tools/import-baras-discipline-abilities.mjs from BARAS ${ref}.\n// Do not edit manually. Re-run the importer when the BARAS reference changes.\n\nexport interface BarasDisciplineAbilityEntry {\n  abilityId: string;\n  ability: string;\n  discipline: string;\n  disciplines: string[];\n  disciplineId: string;\n}\n\nexport const BARAS_DISCIPLINE_ABILITIES_VERSION = ${JSON.stringify(ref)} as const;\nexport const BARAS_DISCIPLINE_ABILITIES: readonly BarasDisciplineAbilityEntry[] = ${JSON.stringify([...byAbilityId.values()].sort((a, b) => a.abilityId.localeCompare(b.abilityId)), null, 2)};\nexport const BARAS_DISCIPLINE_ABILITIES_BY_ID = new Map(BARAS_DISCIPLINE_ABILITIES.map((entry) => [entry.abilityId, entry]));\n`;
const outputPath = resolve(repoRoot, "packages/game-data/src/generated/baras-discipline-abilities.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`Generated ${byAbilityId.size} BARAS discipline-unique ability ids.`);
