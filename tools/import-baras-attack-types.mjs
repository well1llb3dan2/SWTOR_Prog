import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const ref = process.env.BARAS_REF ?? "master";
const response = await fetch(`https://raw.githubusercontent.com/baras-app/baras/${ref}/core/data/attack_types.csv`);
if (!response.ok) throw new Error(`BARAS attack type table request failed: ${response.status}`);
const lines = (await response.text()).split(/\r?\n/).filter(Boolean);
const entries = lines.slice(1).map((line) => {
  const fields = line.split(",");
  const [abilityId, attackType, damageType, ...nameParts] = fields;
  return abilityId && attackType && damageType && /^\d{12,}$/.test(abilityId)
    ? { abilityId, attackType, damageType, name: nameParts.join(",").replace(/^"|"$/g, "") }
    : null;
}).filter((entry) => entry !== null);
const byId = new Map(entries.map((entry) => [entry.abilityId, entry]));
const output = `// Generated by tools/import-baras-attack-types.mjs from BARAS ${ref}.\n// Do not edit manually. Re-run the importer when the BARAS reference changes.\n\nexport interface BarasAttackTypeEntry {\n  abilityId: string;\n  attackType: string;\n  damageType: string;\n  name: string;\n}\n\nexport const BARAS_ATTACK_TYPES_VERSION = ${JSON.stringify(ref)} as const;\nexport const BARAS_ATTACK_TYPES: readonly BarasAttackTypeEntry[] = ${JSON.stringify([...byId.values()].sort((a, b) => a.abilityId.localeCompare(b.abilityId)), null, 2)};\nexport const BARAS_ATTACK_TYPES_BY_ID = new Map(BARAS_ATTACK_TYPES.map((entry) => [entry.abilityId, entry]));\n`;
const outputPath = resolve(repoRoot, "packages/game-data/src/generated/baras-attack-types.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`Generated ${byId.size} BARAS attack type ability ids.`);
